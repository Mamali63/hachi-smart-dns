#!/bin/bash
set -e
PROJ="$(cd "$(dirname "$0")" && pwd)"
SRC="$PROJ/src/main"
WORK="$HOME/apkbuild/dns-app"
JDK="$HOME/apkbuild/jdk17"
BT="$HOME/apkbuild/android-sdk/build-tools/34.0.0"
AJAR="$HOME/apkbuild/android-sdk/platforms/android-34/android.jar"
KS="$HOME/apkbuild/debug.keystore"
export PATH="$JDK/bin:$PATH"
export JAVA_HOME="$JDK"
rm -rf "$WORK"
mkdir -p "$WORK/gen" "$WORK/obj" "$WORK/dex"
echo "== aapt2 compile =="
"$BT/aapt2" compile --dir "$SRC/res" -o "$WORK/compiled_res.zip"
echo "== aapt2 link =="
"$BT/aapt2" link -o "$WORK/unsigned.apk" -I "$AJAR" --manifest "$SRC/AndroidManifest.xml" --java "$WORK/gen" -A "$SRC/assets" "$WORK/compiled_res.zip"
echo "== javac =="
find "$SRC/java" "$WORK/gen" -name "*.java" > "$WORK/sources.txt"
"$JDK/bin/javac" -source 8 -target 8 -encoding UTF-8 -bootclasspath "$AJAR" -cp "$AJAR" -d "$WORK/obj" @"$WORK/sources.txt"
echo "== d8 =="
"$BT/d8" --lib "$AJAR" --min-api 24 --output "$WORK/dex" $(find "$WORK/obj" -name "*.class")
echo "== inject dex =="
cp "$WORK/unsigned.apk" "$WORK/withdex.apk"
(cd "$WORK/dex" && "$JDK/bin/jar" uf "$WORK/withdex.apk" classes.dex)
echo "== zipalign =="
"$BT/zipalign" -f 4 "$WORK/withdex.apk" "$WORK/aligned.apk"
echo "== sign =="
"$BT/apksigner" sign --ks "$KS" --ks-pass pass:android --key-pass pass:android --out "$WORK/hachi-dns.apk" "$WORK/aligned.apk"
echo "== verify =="
"$BT/apksigner" verify --verbose "$WORK/hachi-dns.apk"
"$BT/aapt2" dump badging "$WORK/hachi-dns.apk" | head -5
cp "$WORK/hachi-dns.apk" "$PROJ/hachi-dns.apk"
echo "APK: $WORK/hachi-dns.apk (copied to $PROJ/)"
